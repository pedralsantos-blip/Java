package dia2_practicas;

// Abre la clase para demostrar cómo las comparaciones producen true o false
public class ComparacionesSencillas {
 // Inicia la ejecución del programa
 public static void main(String[] args) {
 // Guardamos en memoria que la persona tiene 17 años
 int edad = 17;
 // Pregunta: ¿17 es mayor o igual que 18? Imprime en consola: false
 System.out.println(edad >= 18);
 // Pregunta: ¿el contenido de edad es exactamente igual a 17? Imprime:
 // true
 System.out.println(edad == 17);
 // Pregunta: ¿17 es diferente de 20? Como sí son distintos, imprime: true
 System.out.println(edad != 20);
 // Cierra el método main
 }
// Cierra la clase ComparacionesSencillas
}
    

