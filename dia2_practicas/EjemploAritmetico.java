
package dia2_practicas;
// Define la clase para probar las cinco operaciones matemáticas básicas
public class EjemploAritmetico {
 // Punto de entrada donde arranca el programa
 public static void main(String[] args) {
 // Guarda el número entero 10 en la variable 'a'
 int a = 10;
 // Guarda el número entero 3 en la variable 'b'
 int b = 3;
 // Suma 10 + 3 y muestra por pantalla el resultado: 13
 System.out.println(a + b);
 // Resta 10 - 3 y muestra por pantalla el resultado: 7
 System.out.println(a - b);
 // Multiplica 10 * 3 y muestra por pantalla el resultado: 30
 System.out.println(a * b);
 // Divide dos números enteros (10 entre 3) y muestra el cociente entero
 // sin decimales: 3
 System.out.println(a / b);
 // Calcula el resto de dividir 10 entre 3 (3*3 es 9, hasta 10 sobra 1) y
 // muestra: 1
 System.out.println(a % b);
 // Cierra el método main
 }
// Cierra la clase EjemploAritmetico
}

    

